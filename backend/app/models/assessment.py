import enum
from sqlalchemy import Column, String, Integer, Float, Boolean, ForeignKey, Enum, DateTime, Text, JSON
from sqlalchemy.orm import relationship
from app.core.database import Base
from app.models.base import TimestampMixin, generate_uuid, utc_now


class AssessmentStatus(str, enum.Enum):
    QUEUED = "QUEUED"
    PREFLIGHT = "PREFLIGHT"
    READY = "READY"
    RUNNING = "RUNNING"
    CANCELLATION_REQUESTED = "CANCELLATION_REQUESTED"
    CANCELLED = "CANCELLED"
    COMPLETED = "COMPLETED"
    PARTIAL = "PARTIAL"
    FAILED = "FAILED"
    REJECTED = "REJECTED"
    TIMED_OUT = "TIMED_OUT"


class FindingSeverity(str, enum.Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"


class FindingConfidence(str, enum.Enum):
    CERTAIN = "CERTAIN"
    FIRM = "FIRM"
    TENTATIVE = "TENTATIVE"


class AssessmentJob(Base, TimestampMixin):
    """
    Persistent assessment execution job.
    Tracks state machine lifecycle, progress, idempotency, provenance, and output limits.
    """
    __tablename__ = "assessment_jobs"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    project_id = Column(String(36), ForeignKey("projects.id", ondelete="CASCADE"), nullable=False, index=True)
    target_id = Column(String(36), ForeignKey("scope_targets.id", ondelete="SET NULL"), nullable=True, index=True)

    target_input = Column(String(500), nullable=False)
    adapter_name = Column(String(100), default="local_fixture_adapter", nullable=False)
    adapter_version = Column(String(50), default="1.0.0", nullable=False)

    # Phase 6A: Typed, versioned execution contract and scope boundary
    policy_version = Column(String(50), default="2026.1", nullable=False)
    authorization_reference = Column(String(255), nullable=True)
    authorization_status = Column(String(50), default="AUTHORIZED", nullable=False)
    scope_snapshot = Column(JSON, default=dict, nullable=False)
    scope_snapshot_digest = Column(String(64), nullable=True, index=True)

    status = Column(Enum(AssessmentStatus), default=AssessmentStatus.QUEUED, nullable=False, index=True)
    idempotency_key = Column(String(100), nullable=True, index=True)
    idempotency_digest = Column(String(64), nullable=True, index=True)
    lock_version = Column(Integer, default=1, nullable=False)

    progress_pct = Column(Integer, default=0, nullable=False)
    queued_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)
    preflight_at = Column(DateTime(timezone=True), nullable=True)
    started_at = Column(DateTime(timezone=True), nullable=True)
    heartbeat_at = Column(DateTime(timezone=True), nullable=True)
    cancellation_requested_at = Column(DateTime(timezone=True), nullable=True)
    completed_at = Column(DateTime(timezone=True), nullable=True)

    timeout_seconds = Column(Integer, default=300, nullable=False)
    attempt_count = Column(Integer, default=1, nullable=False)
    retry_count = Column(Integer, default=0, nullable=False)
    max_retries = Column(Integer, default=2, nullable=False)

    failure_category = Column(String(100), nullable=True, index=True)
    error_message = Column(Text, nullable=True)
    is_simulated = Column(Boolean, default=True, nullable=False)  # Crucial transparency: flags synthetic/fixture execution
    created_by_id = Column(String(36), ForeignKey("users.id", ondelete="RESTRICT"), nullable=False)

    config = Column(JSON, default=dict, nullable=False)
    summary_stats = Column(JSON, default=dict, nullable=False)

    # Relationships
    project = relationship("Project")
    target = relationship("ScopeTarget")
    created_by = relationship("User")
    findings = relationship("AssessmentFinding", back_populates="job", cascade="all, delete-orphan")


class AssessmentFinding(Base):
    """
    Normalized vulnerability finding generated by an assessment execution.
    Retains reference to source job, asset target, severity, confidence, and evidence items.
    """
    __tablename__ = "assessment_findings"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    job_id = Column(String(36), ForeignKey("assessment_jobs.id", ondelete="CASCADE"), nullable=False, index=True)
    project_id = Column(String(36), ForeignKey("projects.id", ondelete="CASCADE"), nullable=False, index=True)

    target_value = Column(String(500), nullable=False)
    title = Column(String(255), nullable=False)
    description = Column(Text, default="", nullable=False)

    severity = Column(Enum(FindingSeverity), default=FindingSeverity.INFO, nullable=False, index=True)
    confidence = Column(Enum(FindingConfidence), default=FindingConfidence.FIRM, nullable=False)
    vuln_id = Column(String(100), nullable=True, index=True)  # e.g., CVE-2026-1049, CWE-89
    cvss_score = Column(Float, nullable=True)

    is_simulated = Column(Boolean, default=True, nullable=False)
    reproduction_steps = Column(Text, default="", nullable=False)
    canonical_finding_id = Column(String(36), ForeignKey("vulnerability_findings.id", ondelete="SET NULL"), nullable=True, index=True)
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)

    # Relationships
    job = relationship("AssessmentJob", back_populates="findings")
    project = relationship("Project")
    evidence_items = relationship("FindingEvidence", back_populates="finding", cascade="all, delete-orphan")
    canonical_finding = relationship("VulnerabilityFinding", back_populates="observations")


class FindingEvidence(Base):
    """
    Cryptographically hashed raw evidence item supporting a vulnerability finding.
    """
    __tablename__ = "finding_evidence"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    finding_id = Column(String(36), ForeignKey("assessment_findings.id", ondelete="CASCADE"), nullable=False, index=True)

    evidence_type = Column(String(100), nullable=False)  # HTTP_EXCHANGE, BANNER, CONFIG, PORT_STATE
    payload = Column(Text, nullable=False)  # Raw evidence text or serialized data
    sha256_hash = Column(String(64), nullable=False, index=True)  # Cryptographic proof of persisted payload
    raw_sha256_hash = Column(String(64), nullable=True)  # Hash of un-truncated raw payload
    is_truncated = Column(Boolean, default=False, nullable=False)
    observed_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)

    # Relationships
    finding = relationship("AssessmentFinding", back_populates="evidence_items")
